package main

import "fmt"

func main() {
	// Variáveis Valores Zero
	var a int     // int - (inteiro)
	var b float64 // float - (float64/float32 - decimal)
	var c bool    // bool - (verdadeiro ou falso)
	var d string  // string - (sequência de bytes)

	//Exibindo as Variáveis
	fmt.Printf("int: %v\n", a)
	fmt.Printf("float: %v\n", b)
	fmt.Printf("bool: %v\n", c)
	fmt.Printf("string: %q\n", d)
}
